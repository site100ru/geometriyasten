<?php
	// =====================================================================
	// КАПЧА «ПРИМЕР НА СЛОЖЕНИЕ» — защита форм от роботов
	// =====================================================================
	//
	// Как это работает целиком (3 файла):
	//
	//   1. index.php — в формах «Получить скидку» и «Обратный звонок» есть
	//      картинка <img class="captchaImg"> и поле <input name="captcha">.
	//      Когда посетитель открывает окно с формой, скрипт внизу index.php
	//      загружает эту картинку — то есть открывает ЭТОТ файл (captcha.php).
	//
	//   2. captcha.php (этот файл) — придумывает пример (например, 3 + 5),
	//      рисует его картинкой и запоминает правильный ответ (8) в СЕССИИ.
	//      Сессия — это память сервера о конкретном посетителе: браузер
	//      хранит только «номер» сессии в cookie, а сам ответ лежит на сервере,
	//      поэтому подсмотреть его в коде страницы невозможно.
	//
	//   3. callback-mail.php — получает отправленную форму и сравнивает то,
	//      что ввёл посетитель в поле «Ответ на пример», с ответом из сессии.
	//      Совпало — заявка отправляется. Не совпало — показываем ошибку.
	//
	// Для работы нужно PHP-расширение GD (рисует картинки). На хостинге оно
	// обычно включено; если его нет — картинка не появится.
	// =====================================================================

	// Включаем сессию, чтобы было куда записать правильный ответ
	session_start();

	// Два случайных числа от 1 до 9
	$a = rand( 1, 9 );
	$b = rand( 1, 9 );

	// Запоминаем правильный ответ. Ключ 'captcha' читает callback-mail.php.
	// Каждый новый показ картинки перезаписывает ответ — действует только
	// последний показанный пример.
	$_SESSION['captcha'] = $a + $b;

	// Сообщаем браузеру, что отдаём картинку PNG, а не обычную страницу
	header( 'Content-Type: image/png' );

	// Запрещаем браузеру кешировать картинку, иначе после обновления
	// пользователь увидит старый пример, а в сессии будет уже новый ответ
	header( 'Cache-Control: no-store, no-cache, must-revalidate' );
	header( 'Pragma: no-cache' );

	// Создаём пустую картинку 120×40 пикселей и задаём цвета:
	// светло-серый фон и почти чёрный текст (числа — это красный, зелёный, синий)
	$img = imagecreatetruecolor( 120, 40 );
	$bg  = imagecolorallocate( $img, 240, 240, 240 );
	$fg  = imagecolorallocate( $img, 30, 30, 30 );
	imagefill( $img, 0, 0, $bg );

	// Шум: 30 случайных линий случайного бледного цвета поверх фона,
	// чтобы пример сложнее было распознать программой
	for ( $i = 0; $i < 30; $i++ ) {
		$c = imagecolorallocate( $img, rand( 150, 220 ), rand( 150, 220 ), rand( 150, 220 ) );
		imageline( $img, rand( 0, 120 ), rand( 0, 40 ), rand( 0, 120 ), rand( 0, 40 ), $c );
	}

	// Пишем сам пример встроенным шрифтом PHP:
	// 5 — размер шрифта (самый крупный из встроенных), 22 и 12 — отступ слева и сверху
	imagestring( $img, 5, 22, 12, "$a + $b = ?", $fg );

	// Отдаём готовую картинку в браузер и освобождаем память
	imagepng( $img );
	imagedestroy( $img );
