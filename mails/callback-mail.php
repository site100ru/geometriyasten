<?php
session_start();

// Подключаем WordPress, чтобы прочитать настройки из «Внешний вид → Настроить».
// Этот файл открывается напрямую (не через тему), поэтому сам WordPress
// здесь не загружен. dirname(__DIR__, 4) — папка сайта, где лежит wp-load.php
// (на 4 уровня выше папки mails: mails → тема → themes → wp-content → сайт).
require_once dirname(__DIR__, 4) . '/wp-load.php';

// Если существует переменная POST, то обрабатываем форму
if ( $_POST ) {

	// Токен и ID чата для Telegram бота — задаются в админке:
	// «Внешний вид → Настроить → Telegram-бот для заявок» (см. functions.php)
	$token = trim( get_theme_mod( 'geometriyasten_telegram_token', '' ) );
	$chat_id = trim( get_theme_mod( 'geometriyasten_telegram_chat_id', '' ) );

	// Получаем данные из формы
	$name = isset($_POST['name']) && $_POST['name'] ? $_POST['name'] : 'Не указано';
	$tel = isset($_POST['tel']) ? $_POST['tel'] : '';

	// Проверяем, что телефон введён точно по маске +7(999)999-99-99.
	// Если номер не дописан или записан в другом виде — заявку не отправляем.
	//
	// Как читать шаблон ниже:
	//   ^        — номер должен начинаться сразу, без лишних символов впереди
	//   \+       — знак плюс (обратная косая черта «\» нужна, чтобы плюс
	//              считался обычным символом, а не командой шаблона)
	//   7        — цифра семь (маска на сайте всегда подставляет именно её)
	//   \(       — открывающая скобка (косая черта — по той же причине, что у плюса)
	//   \d{3}    — три цифры (код оператора)
	//   \)       — закрывающая скобка
	//   \d{3}    — три цифры
	//   -        — дефис
	//   \d{2}    — две цифры
	//   -        — дефис
	//   \d{2}    — две цифры
	//   \z       — на этом номер заканчивается, после него ничего быть не должно
	//
	// is_string() проверяет, что телефон пришёл обычным текстом.
	// Без неё поддельная отправка формы могла бы вызвать ошибку на сайте.
	if ( !is_string( $tel ) || !preg_match( '/^\+7\(\d{3}\)\d{3}-\d{2}-\d{2}\z/', $tel ) ) {
		// Номер заполнен не полностью — заявка не отправляется
		header("Location: ".$_SERVER['HTTP_REFERER']);
		exit;
	}

	// ---------------------------------------------------------------------
	// КАПЧА: проверяем ответ на пример со сложением.
	// Подробное описание всей схемы — в начале файла mails/captcha.php.
	//
	// Коротко: когда посетитель открыл форму, mails/captcha.php нарисовал
	// картинку с примером (например, 3 + 5) и запомнил в сессии правильный
	// ответ — $_SESSION['captcha'] = 8. Здесь мы сравниваем его с тем,
	// что посетитель ввёл в поле «Ответ на пример» (name="captcha").
	// ---------------------------------------------------------------------

	// Достаём правильный ответ из сессии. Если его там нет (картинку
	// не открывали — так обычно делают роботы), получаем null.
	$captcha = isset($_SESSION['captcha']) ? $_SESSION['captcha'] : null;

	// Сразу удаляем ответ из сессии, чтобы один и тот же ответ нельзя было
	// использовать для нескольких отправок подряд. Для новой попытки
	// посетителю покажут новый пример.
	unset($_SESSION['captcha']);

	// Ответ, который ввёл посетитель
	$answer = isset($_POST['captcha']) ? $_POST['captcha'] : '';

	// Заявку отклоняем, если выполняется хотя бы одно условие (|| — «или»):
	//   $captcha === null            — пример не показывали (картинка не загружалась)
	//   !is_string( $answer )        — ответ пришёл не текстом (поддельная отправка формы)
	//   !preg_match( '/^\d{1,2}\z/' ) — ответ не из 1–2 цифр (сумма двух чисел
	//                                  от 1 до 9 — это максимум 18). trim()
	//                                  убирает случайные пробелы по краям
	//   (int) ... !== $captcha       — число не совпадает с правильным ответом
	if ( $captcha === null || !is_string( $answer ) || !preg_match( '/^\d{1,2}\z/', trim( $answer ) ) || (int) trim( $answer ) !== $captcha ) {
		// Ответ неверный или пример не был показан — заявка не отправляется
		$_SESSION['win'] = 1;
		$_SESSION['recaptcha'] = '<p class="text-light"><strong>Ошибка!</strong><br>Неверный ответ на пример. Попробуйте еще раз.</p>';
		header("Location: ".$_SERVER['HTTP_REFERER']);
		exit;
	}

	// Формируем базовое сообщение
	$message = "Заявка на вызов специалиста с сайта geometriyasten62.ru\n";
	$message .= "Имя: " . $name . "\n";
	$message .= "Телефон: " . $tel . "\n";

	$email_message = "Заявка на вызов специалиста с сайта geometriyasten62.ru\n\n";
	$email_message .= "Имя: " . $name . "\n";
	$email_message .= "Телефон: " . $tel . "\n";

	// Если есть ссылка - добавляем её в сообщение
	if (isset($_POST['link']) && !empty($_POST['link'])) {
		$link = $_POST['link'];
		$message .= "Ссылка на предложение конкурента: " . $link . "\n";
		$email_message .= "Ссылка на предложение конкурента: " . $link . "\n";
	}

	// Отправляем на email
	$email_sent = mail("vasilyev-r@yandex.ru, sidorov-vv3@mail.ru", "Заявка на вызов специалиста с сайта geometriyasten62.ru", $email_message);

	// Отправляем в Telegram (только если токен и ID чата заполнены в настройках)
	$telegram_sent = false;
	if ( $token !== '' && $chat_id !== '' ) {
		$telegram_url = "https://api.telegram.org/bot{$token}/sendMessage?chat_id=" . urlencode($chat_id) . "&text=" . urlencode($message);
		$telegram_sent = file_get_contents($telegram_url);
	}

	// Проверяем успешность отправки
	if ($email_sent || $telegram_sent) {
		$_SESSION['win'] = 1;
		$_SESSION['recaptcha'] = '<p class="text-light">Спасибо за заявку! Мы свяжемся с Вами в ближайшее время.</p>';
	} else {
		$_SESSION['win'] = 1;
		$_SESSION['recaptcha'] = '<p class="text-light"><strong>Ошибка!</strong><br>Не удалось отправить заявку. Попробуйте еще раз.</p>';
	}

	// Перенаправляем пользователя обратно на страницу
	header("Location: ".$_SERVER['HTTP_REFERER']);
	exit;
}
?>
